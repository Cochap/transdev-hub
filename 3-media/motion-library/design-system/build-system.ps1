# Reads design-tokens.json and writes tokens.css and design-preview.html.
# Also measures WCAG contrast for the colour pairs listed in contrastPairs.
# Usage: powershell -NoProfile -ExecutionPolicy Bypass -File build-system.ps1
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$tok = Get-Content (Join-Path $root 'design-tokens.json') -Raw -Encoding UTF8 | ConvertFrom-Json

function Get-Lum([string]$hex) {
  $h = $hex.TrimStart('#')
  $c = @(0, 2, 4) | ForEach-Object {
    $v = [Convert]::ToInt32($h.Substring($_, 2), 16) / 255
    if ($v -le 0.03928) { $v / 12.92 } else { [Math]::Pow(($v + 0.055) / 1.055, 2.4) }
  }
  0.2126 * $c[0] + 0.7152 * $c[1] + 0.0722 * $c[2]
}
function Get-Contrast([string]$a, [string]$b) {
  $la = Get-Lum $a; $lb = Get-Lum $b
  $hi = [Math]::Max($la, $lb); $lo = [Math]::Min($la, $lb)
  [Math]::Round(($hi + 0.05) / ($lo + 0.05), 2)
}
function Resolve-Role([string]$role) {
  $name = $tok.colorRoles.PSObject.Properties[$role].Value
  $tok.color.PSObject.Properties[$name].Value.value
}

# ---- tokens.css ----
$css = New-Object System.Collections.Generic.List[string]
$css.Add('/* Generated by build-system.ps1 from design-tokens.json. Do not edit by hand. */')
$css.Add(':root{')
foreach ($p in $tok.color.PSObject.Properties) { $css.Add("  --palette-$($p.Name): $($p.Value.value);") }
foreach ($p in $tok.colorRoles.PSObject.Properties) { $css.Add("  --color-$($p.Name): var(--palette-$($p.Value));") }
$css.Add("  --font-family: $($tok.typography.family.value);")
foreach ($p in $tok.typography.scale.PSObject.Properties) {
  $n = $p.Name; $s = $p.Value
  $css.Add("  --type-$n-size: $($s.size);"); $css.Add("  --type-$n-line: $($s.line);")
  $css.Add("  --type-$n-weight: $($s.weight);"); $css.Add("  --type-$n-tracking: $($s.tracking);")
}
foreach ($p in $tok.shape.PSObject.Properties) { $css.Add("  --shape-$($p.Name): $($p.Value.value)px;") }
foreach ($p in $tok.spacing.PSObject.Properties) {
  if ($p.Name -eq 'status') { continue }
  if ($p.Value -is [ValueType]) { $css.Add("  --space-$($p.Name): $($p.Value)px;") } else { $css.Add("  --space-$($p.Name): $($p.Value.value);") }
}
foreach ($p in $tok.elevation.PSObject.Properties) { $css.Add("  --elevation-$($p.Name): $($p.Value.value);") }
foreach ($p in $tok.motion.duration.PSObject.Properties) { if ($p.Name -ne 'status') { $css.Add("  --duration-$($p.Name): $($p.Value)ms;") } }
foreach ($p in $tok.motion.easing.PSObject.Properties) { $css.Add("  --ease-$($p.Name): $($p.Value.value);") }
foreach ($p in $tok.motion.role.PSObject.Properties) {
  if ($p.Value.token) { $css.Add("  --motion-$($p.Name): var(--duration-$($p.Value.token));") } else { $css.Add("  --motion-$($p.Name): $($p.Value.ms)ms;") }
}
$css.Add("  --motion-stagger: $($tok.motion.stagger.ms)ms;")
$css.Add("  --motion-distance-xs: $($tok.motion.distance.xs.px)px;")
$css.Add("  --motion-distance-sm: $($tok.motion.distance.sm.px)px;")
$css.Add("  --motion-scale-in: $($tok.motion.'scale-in'.value);")
$css.Add('}')
$rm = "  --motion-soft-micro: $($tok.motion.reducedMotion.ms)ms; --motion-soft-ui: $($tok.motion.reducedMotion.ms)ms; --motion-soft-reveal: $($tok.motion.reducedMotion.ms)ms; --motion-stagger: 0ms; --motion-distance-xs: 0px; --motion-distance-sm: 0px; --motion-scale-in: 1;"
$css.Add('@media (prefers-reduced-motion: reduce){:root{'); $css.Add($rm); $css.Add('}}')
$css.Add(':root[data-reduced="true"]{'); $css.Add($rm); $css.Add('}')
[IO.File]::WriteAllText((Join-Path $root 'tokens.css'), ($css -join "`n"), (New-Object Text.UTF8Encoding($false)))

# ---- contrast ----
$rows = @()
foreach ($pair in $tok.contrastPairs) {
  $fg = Resolve-Role $pair[0]; $bg = Resolve-Role $pair[1]
  $r = Get-Contrast $fg $bg
  $rows += [pscustomobject]@{ fg = $pair[0]; bg = $pair[1]; fgHex = $fg; bgHex = $bg; ratio = $r; aa = ($r -ge 4.5); aaLarge = ($r -ge 3) }
}
$rows | ForEach-Object { "{0,-20} on {1,-18} {2,6}:1  AA text: {3,-5}  AA large: {4}" -f $_.fg, $_.bg, $_.ratio, $_.aa, $_.aaLarge }

# ---- design-preview.html ----
$jsonText = (Get-Content (Join-Path $root 'design-tokens.json') -Raw -Encoding UTF8) -replace '</', '<\/'
$contrastText = ($rows | ConvertTo-Json -Compress -Depth 4) -replace '</', '<\/'
if ($rows.Count -eq 1) { $contrastText = "[$contrastText]" }
$tpl = Get-Content (Join-Path $root 'preview.template.html') -Raw -Encoding UTF8
$html = $tpl.Replace('__TOKENS_CSS__', ($css -join "`n")).Replace('__TOKENS_JSON__', $jsonText).Replace('__CONTRAST_JSON__', $contrastText).Replace('__DATE__', (Get-Date -Format 'yyyy-MM-dd'))
[IO.File]::WriteAllText((Join-Path $root 'design-preview.html'), $html, (New-Object Text.UTF8Encoding($false)))
"Built tokens.css and design-preview.html"
